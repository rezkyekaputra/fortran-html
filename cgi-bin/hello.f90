! ============================================================
! Demo Website Fortran via CGI
! Dibuat oleh: Cefneal
! Deskripsi: Program Fortran yang output HTML ke browser
! ============================================================
program hello_web
  implicit none

  ! Variabel untuk data
  integer :: i
  real    :: nilai(5)
  character(len=20) :: nama(5)

  ! Data dummy
  nama  = ["Budi    ", "Siti    ", "Andi    ", "Rina    ", "Doni    "]
  nilai = [92.5, 87.0, 95.5, 78.0, 88.5]

  ! === CGI Header ===
  write(*,'(A)') "Content-Type: text/html; charset=UTF-8"
  write(*,'(A)') ""

  ! === HTML Output ===
  write(*,'(A)') "<!DOCTYPE html>"
  write(*,'(A)') "<html lang='id'>"
  write(*,'(A)') "<head>"
  write(*,'(A)') "  <meta charset='UTF-8'>"
  write(*,'(A)') "  <meta name='viewport' content='width=device-width, initial-scale=1.0'>"
  write(*,'(A)') "  <title>Website Fortran!</title>"
  write(*,'(A)') "  <style>"
  write(*,'(A)') "    * { margin: 0; padding: 0; box-sizing: border-box; }"
  write(*,'(A)') "    body { font-family: 'Courier New', monospace; background: #1d2021; color: #ebdbb2; min-height: 100vh; display: flex; flex-direction: column; align-items: center; justify-content: center; padding: 2rem; }"
  write(*,'(A)') "    .card { background: #282828; border: 2px solid #458588; border-radius: 8px; padding: 2rem; max-width: 600px; width: 100%; box-shadow: 0 0 30px rgba(69,133,136,0.3); }"
  write(*,'(A)') "    h1 { color: #83a598; font-size: 1.8rem; margin-bottom: 0.5rem; }"
  write(*,'(A)') "    .badge { display: inline-block; background: #d65d0e; color: #fbf1c7; padding: 2px 10px; border-radius: 4px; font-size: 0.8rem; margin-bottom: 1.5rem; }"
  write(*,'(A)') "    table { width: 100%; border-collapse: collapse; margin-top: 1rem; }"
  write(*,'(A)') "    th { background: #3c3836; color: #fabd2f; padding: 10px; text-align: left; border-bottom: 2px solid #504945; }"
  write(*,'(A)') "    td { padding: 10px; border-bottom: 1px solid #3c3836; }"
  write(*,'(A)') "    tr:hover td { background: #32302f; }"
  write(*,'(A)') "    .nilai { color: #b8bb26; font-weight: bold; }"
  write(*,'(A)') "    .footer { margin-top: 1.5rem; color: #928374; font-size: 0.85rem; text-align: center; }"
  write(*,'(A)') "    .footer span { color: #d3869b; }"
  write(*,'(A)') "  </style>"
  write(*,'(A)') "</head>"
  write(*,'(A)') "<body>"
  write(*,'(A)') "  <div class='card'>"
  write(*,'(A)') "    <h1>🖥️ Website dari Fortran!</h1>"
  write(*,'(A)') "    <span class='badge'>GNU Fortran 14.3.1 · CGI</span>"
  write(*,'(A)') "    <p>Ini adalah halaman HTML yang di-generate langsung oleh program <strong>Fortran</strong>.</p>"
  write(*,'(A)') "    <table>"
  write(*,'(A)') "      <thead>"
  write(*,'(A)') "        <tr><th>#</th><th>Nama</th><th>Nilai</th><th>Grade</th></tr>"
  write(*,'(A)') "      </thead>"
  write(*,'(A)') "      <tbody>"

  ! Loop data → baris tabel HTML
  do i = 1, 5
    write(*,'(A)') "        <tr>"
    write(*,'(A,I1,A)') "          <td>", i, "</td>"
    write(*,'(A,A,A)') "          <td>", trim(adjustl(nama(i))), "</td>"
    write(*,'(A,F5.1,A)') "          <td class='nilai'>", nilai(i), "</td>"
    if (nilai(i) >= 90.0) then
      write(*,'(A)') "          <td>🏆 A</td>"
    else if (nilai(i) >= 80.0) then
      write(*,'(A)') "          <td>✅ B</td>"
    else
      write(*,'(A)') "          <td>📝 C</td>"
    end if
    write(*,'(A)') "        </tr>"
  end do

  write(*,'(A)') "      </tbody>"
  write(*,'(A)') "    </table>"
  write(*,'(A)') "    <div class='footer'>Generated by <span>Fortran</span> · Gruvbox Dark Theme · 2026</div>"
  write(*,'(A)') "  </div>"
  write(*,'(A)') "</body>"
  write(*,'(A)') "</html>"

end program hello_web
