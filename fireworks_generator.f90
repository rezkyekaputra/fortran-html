  write(unit_html,'(A)') "      for (let i = particles.length - 1; i >= 0; i--) {"
  write(unit_html,'(A)') "        particles[i].update();"
  write(unit_html,'(A)') "        particles[i].draw();"
  write(unit_html,'(A)') "        if (particles[i].life <= 0) particles.splice(i, 1);"
  write(unit_html,'(A)') "      }"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "      requestAnimationFrame(loop);"
  write(unit_html,'(A)') "    }"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    launchRainbowShell();"
  write(unit_html,'(A)') "    setInterval(launchRainbowShell, 6500);"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    loop();"
  write(unit_html,'(A)') "  </script>"
  write(unit_html,'(A)') "</body>"
  write(unit_html,'(A)') "</html>"
  close(unit_html)
  print *, "index.html Nagaoka Pelangi Siang sukses dibuat!"

