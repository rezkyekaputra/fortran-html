  ! ------------------------------------------------------------
  ! 2. GENERATE INDEX.HTML SIANG HARI TANPA SUARA & TANPA KLIK
  ! ------------------------------------------------------------
  open(newunit=unit_html, file="/home/dongkrak/fortran-web/index.html", status="replace")
  write(unit_html,'(A)') "<!DOCTYPE html>"
  write(unit_html,'(A)') "<html lang='ja'>"
  write(unit_html,'(A)') "<head>"
  write(unit_html,'(A)') "  <meta charset='UTF-8'>"
  write(unit_html,'(A)') "  <meta name='viewport' content='width=device-width, initial-scale=1.0'>"
  write(unit_html,'(A)') "  <title>長岡昼花火・正三尺玉 (Nagaoka Daytime Hanabi) ☀️🎆</title>"
  write(unit_html,'(A)') "  <link rel='stylesheet' href='fireworks.css?v=daytime_v1'>"
  write(unit_html,'(A)') "</head>"
  write(unit_html,'(A)') "<body>"
  write(unit_html,'(A)') "  <div class='stage'>"
  write(unit_html,'(A)') "    <div class='daytime-clouds'></div>"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    <div class='overlay'>"
  write(unit_html,'(A)') "      <h1>長岡昼花火 · 正三尺玉</h1>"
  write(unit_html,'(A)') "      <p class='sub'>NAGAOKA DAYTIME SHOSAN-SHAKUDAMA · AZURE SKY & SMOKE KAMURO</p>"
  write(unit_html,'(A)') "      <div class='day-badge'>"
  write(unit_html,'(A)') "        <span>☀️ Tema: Siang Hari (昼花火)</span>"
  write(unit_html,'(A)') "        <span>·</span>"
  write(unit_html,'(A)') "        <span>🔇 Suara: Nonaktif</span>"
  write(unit_html,'(A)') "        <span>·</span>"
  write(unit_html,'(A)') "        <span>✨ Otomatis Meluncur</span>"
  write(unit_html,'(A)') "      </div>"
  write(unit_html,'(A)') "    </div>"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    <canvas id='hanabiCanvas' class='hanabi-canvas'></canvas>"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    <div class='daytime-landscape'>"
  write(unit_html,'(A)') "      <div class='city-expanse-day'></div>"
  write(unit_html,'(A)') "      <div class='hills-foreground'></div>"
  write(unit_html,'(A)') "    </div>"
  write(unit_html,'(A)') "  </div>"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "  <script>"
  write(unit_html,'(A)') "    const canvas = document.getElementById('hanabiCanvas');"
  write(unit_html,'(A)') "    const ctx = canvas.getContext('2d');"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    function resize() {"
  write(unit_html,'(A)') "      canvas.width = window.innerWidth;"
  write(unit_html,'(A)') "      canvas.height = window.innerHeight;"
  write(unit_html,'(A)') "    }"
  write(unit_html,'(A)') "    window.addEventListener('resize', resize);"
  write(unit_html,'(A)') "    resize();"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    const particles = [];"
  write(unit_html,'(A)') "    let shellAscending = true;"
  write(unit_html,'(A)') "    let rocketY = 0;"
  write(unit_html,'(A)') "    let rocketTargetY = 0;"
  write(unit_html,'(A)') "    let rocketX = 0;"
  write(unit_html,'(A)') "    let rocketVy = -11;"
  write(unit_html,'(A)') "    const rocketTrail = [];"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    function launchDaytimeShell() {"
  write(unit_html,'(A)') "      shellAscending = true;"
  write(unit_html,'(A)') "      rocketX = canvas.width * (0.35 + Math.random() * 0.15);"
  write(unit_html,'(A)') "      rocketY = canvas.height * 0.95;"
  write(unit_html,'(A)') "      rocketTargetY = canvas.height * 0.35;"
  write(unit_html,'(A)') "      rocketVy = - (9.8 + Math.random() * 1.5);"
  write(unit_html,'(A)') "      rocketTrail.length = 0;"
  write(unit_html,'(A)') "    }"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    class DaytimeParticle {"
  write(unit_html,'(A)') "      constructor(x, y, vx, vy, color, isKamuro, life) {"
  write(unit_html,'(A)') "        this.x = x;"
  write(unit_html,'(A)') "        this.y = y;"
  write(unit_html,'(A)') "        this.vx = vx;"
  write(unit_html,'(A)') "        this.vy = vy;"
  write(unit_html,'(A)') "        this.color = color;"
  write(unit_html,'(A)') "        this.isKamuro = isKamuro;"
  write(unit_html,'(A)') "        this.life = life;"
  write(unit_html,'(A)') "        this.maxLife = life;"
  write(unit_html,'(A)') "        this.trail = [];"
  write(unit_html,'(A)') "        this.maxTrail = isKamuro ? 26 : 12;"
  write(unit_html,'(A)') "      }"
  write(unit_html,'(A)') "      update() {"
  write(unit_html,'(A)') "        this.trail.push({x: this.x, y: this.y});"
  write(unit_html,'(A)') "        if (this.trail.length > this.maxTrail) this.trail.shift();"
  write(unit_html,'(A)') "        this.x += this.vx;"
  write(unit_html,'(A)') "        this.y += this.vy;"
  write(unit_html,'(A)') "        if (this.isKamuro) {"
  write(unit_html,'(A)') "          this.vx *= 0.978; "
  write(unit_html,'(A)') "          this.vy *= 0.985;"
  write(unit_html,'(A)') "          this.vy += 0.052; // Tarikan gravitasi lurus ke bawah"
  write(unit_html,'(A)') "        } else {"
  write(unit_html,'(A)') "          this.vx *= 0.96;"
  write(unit_html,'(A)') "          this.vy *= 0.96;"
  write(unit_html,'(A)') "          this.vy += 0.035;"
  write(unit_html,'(A)') "        }"
  write(unit_html,'(A)') "        this.life--;"
  write(unit_html,'(A)') "      }"
  write(unit_html,'(A)') "      draw() {"
  write(unit_html,'(A)') "        if (this.trail.length < 2) return;"
  write(unit_html,'(A)') "        const alpha = Math.max(0, this.life / this.maxLife);"
  write(unit_html,'(A)') "        ctx.beginPath();"
  write(unit_html,'(A)') "        ctx.moveTo(this.trail[0].x, this.trail[0].y);"
  write(unit_html,'(A)') "        for (let i = 1; i < this.trail.length; i++) {"
  write(unit_html,'(A)') "          ctx.lineTo(this.trail[i].x, this.trail[i].y);"
  write(unit_html,'(A)') "        }"
  write(unit_html,'(A)') "        ctx.strokeStyle = this.color;"
  write(unit_html,'(A)') "        ctx.globalAlpha = alpha * 0.9;"
  write(unit_html,'(A)') "        ctx.lineWidth = this.isKamuro ? 2.0 : 3.2;"
  write(unit_html,'(A)') "        ctx.lineCap = 'round';"
  write(unit_html,'(A)') "        ctx.stroke();"
  write(unit_html,'(A)') "        ctx.globalAlpha = 1.0;"
  write(unit_html,'(A)') "      }"
  write(unit_html,'(A)') "    }"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    function explodeDaytimeDome(cx, cy) {"
  write(unit_html,'(A)') "      // 1. KUBAH EMAS SIANG HARI (ORANYE TEMBAGA & EMAS TERANG KONTRAS LANGIT)"
  write(unit_html,'(A)') "      const domeCount = 360;"
  write(unit_html,'(A)') "      for (let i = 0; i < domeCount; i++) {"
  write(unit_html,'(A)') "        const angle = Math.random() * Math.PI * 2;"
  write(unit_html,'(A)') "        const speed = 2.2 + Math.random() * 5.0;"
  write(unit_html,'(A)') "        const vx = Math.cos(angle) * speed * 1.35;"
  write(unit_html,'(A)') "        let vy = Math.sin(angle) * speed;"
  write(unit_html,'(A)') "        if (vy > 0) vy *= 0.55;"
  write(unit_html,'(A)') "        // Warna pigmen tebal agar kontras jelas di langit siang"
  write(unit_html,'(A)') "        const dayColors = ['#d35400', '#e67e22', '#b71540', '#f39c12', '#c0392b'];"
  write(unit_html,'(A)') "        const col = dayColors[Math.floor(Math.random() * dayColors.length)];"
  write(unit_html,'(A)') "        particles.push(new DaytimeParticle(cx, cy, vx, vy, col, true, 160 + Math.random() * 50));"
  write(unit_html,'(A)') "      }"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "      // 2. INTI BINTANG WARNA PEKAT SIANG HARI (MERAH, HIJAU, BIRU TUA, MAGENTA)"
  write(unit_html,'(A)') "      const coreColors = ['#009432', '#ea2027', '#0652dd', '#8854d0', '#ff3838'];"
  write(unit_html,'(A)') "      const coreCount = 80;"
  write(unit_html,'(A)') "      for (let i = 0; i < coreCount; i++) {"
  write(unit_html,'(A)') "        const angle = Math.random() * Math.PI * 2;"
  write(unit_html,'(A)') "        const speed = 1.4 + Math.random() * 3.0;"
  write(unit_html,'(A)') "        const vx = Math.cos(angle) * speed * 1.2;"
  write(unit_html,'(A)') "        const vy = Math.sin(angle) * speed * 1.2;"
  write(unit_html,'(A)') "        const col = coreColors[i % coreColors.length];"
  write(unit_html,'(A)') "        particles.push(new DaytimeParticle(cx, cy, vx, vy, col, false, 80 + Math.random() * 25));"
  write(unit_html,'(A)') "      }"
  write(unit_html,'(A)') "    }"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    function loop() {"
  write(unit_html,'(A)') "      // Jejak Menghilang Halus di Latar Langit Siang Cerah"
  write(unit_html,'(A)') "      ctx.globalCompositeOperation = 'destination-out';"
  write(unit_html,'(A)') "      ctx.fillStyle = 'rgba(0, 0, 0, 0.08)';"
  write(unit_html,'(A)') "      ctx.fillRect(0, 0, canvas.width, canvas.height);"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "      // Mode Gambar Standar (Source-Over) agar Warna Kontras Pekat di Siang Hari"
  write(unit_html,'(A)') "      ctx.globalCompositeOperation = 'source-over';"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "      // Animasi Roket Asap Putih Menjulang Naik"
  write(unit_html,'(A)') "      if (shellAscending) {"
  write(unit_html,'(A)') "        rocketTrail.push({x: rocketX, y: rocketY});"
  write(unit_html,'(A)') "        if (rocketTrail.length > 8) rocketTrail.shift();"
  write(unit_html,'(A)') "        rocketY += rocketVy;"
  write(unit_html,'(A)') "        rocketVy *= 0.985;"
  write(unit_html,'(A)') "        ctx.beginPath();"
  write(unit_html,'(A)') "        ctx.strokeStyle = '#ffffff';"
  write(unit_html,'(A)') "        ctx.lineWidth = 4.0;"
  write(unit_html,'(A)') "        for (let i = 0; i < rocketTrail.length; i++) {"
  write(unit_html,'(A)') "          ctx.lineTo(rocketTrail[i].x, rocketTrail[i].y);"
  write(unit_html,'(A)') "        }"
  write(unit_html,'(A)') "        ctx.stroke();"
  write(unit_html,'(A)') "        if (rocketY <= rocketTargetY || Math.abs(rocketVy) < 1.4) {"
  write(unit_html,'(A)') "          shellAscending = false;"
  write(unit_html,'(A)') "          explodeDaytimeDome(rocketX, rocketY);"
  write(unit_html,'(A)') "        }"
  write(unit_html,'(A)') "      }"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "      // Render & Update Partikel Kubah Siang"
  write(unit_html,'(A)') "      for (let i = particles.length - 1; i >= 0; i--) {"
  write(unit_html,'(A)') "        particles[i].update();"
  write(unit_html,'(A)') "        particles[i].draw();"
  write(unit_html,'(A)') "        if (particles[i].life <= 0) particles.splice(i, 1);"
  write(unit_html,'(A)') "      }"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "      requestAnimationFrame(loop);"
  write(unit_html,'(A)') "    }"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    launchDaytimeShell();"
  write(unit_html,'(A)') "    setInterval(launchDaytimeShell, 6500);"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    loop();"
  write(unit_html,'(A)') "  </script>"
  write(unit_html,'(A)') "</body>"
  write(unit_html,'(A)') "</html>"
  close(unit_html)
  print *, "index.html Nagaoka Siang Hari sukses dibuat!"

end program daytime_hanabi_engine
