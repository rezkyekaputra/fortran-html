  write(unit_html,'(A)') "        this.y = y;"
  write(unit_html,'(A)') "        this.vx = vx;"
  write(unit_html,'(A)') "        this.vy = vy;"
  write(unit_html,'(A)') "        this.color = color;"
  write(unit_html,'(A)') "        this.isKamuro = isKamuro;"
  write(unit_html,'(A)') "        this.life = life;"
  write(unit_html,'(A)') "        this.maxLife = life;"
  write(unit_html,'(A)') "        this.trail = [];"
  write(unit_html,'(A)') "        this.maxTrail = isKamuro ? 28 : 14;"
  write(unit_html,'(A)') "      }"
  write(unit_html,'(A)') "      update() {"
  write(unit_html,'(A)') "        this.trail.push({x: this.x, y: this.y});"
  write(unit_html,'(A)') "        if (this.trail.length > this.maxTrail) this.trail.shift();"
  write(unit_html,'(A)') "        this.x += this.vx;"
  write(unit_html,'(A)') "        this.y += this.vy;"
  write(unit_html,'(A)') "        if (this.isKamuro) {"
  write(unit_html,'(A)') "          this.vx *= 0.978; "
  write(unit_html,'(A)') "          this.vy *= 0.985;"
  write(unit_html,'(A)') "          this.vy += 0.052; // Gravitasi menarik jatuh vertikal"
  write(unit_html,'(A)') "        } else {"
  write(unit_html,'(A)') "          this.vx *= 0.96;"
  write(unit_html,'(A)') "          this.vy *= 0.96;"
  write(unit_html,'(A)') "          this.vy += 0.035;"
  write(unit_html,'(A)') "        }"
  write(unit_html,'(A)') "        this.life--;"
  write(unit_html,'(A)') "      }"
