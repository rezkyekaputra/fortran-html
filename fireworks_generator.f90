  write(unit_html,'(A)') "      for (let i = 0; i < domeCount; i++) {"
  write(unit_html,'(A)') "        const angle = Math.random() * Math.PI * 2;"
  write(unit_html,'(A)') "        const speed = 2.2 + Math.random() * 5.2;"
  write(unit_html,'(A)') "        const vx = Math.cos(angle) * speed * 1.35;"
  write(unit_html,'(A)') "        let vy = Math.sin(angle) * speed;"
  write(unit_html,'(A)') "        if (vy > 0) vy *= 0.55;"
  write(unit_html,'(A)') "        // Pemetaan Sudut ke Warna Spektrum Pelangi Melingkar!"
  write(unit_html,'(A)') "        const normalizedAngle = (angle + Math.PI) / (Math.PI * 2);"
  write(unit_html,'(A)') "        const colorIdx = Math.floor(normalizedAngle * rainbowPalette.length) % rainbowPalette.length;"
  write(unit_html,'(A)') "        const col = rainbowPalette[colorIdx];"
  write(unit_html,'(A)') "        particles.push(new RainbowParticle(cx, cy, vx, vy, col, true, 160 + Math.random() * 50));"
  write(unit_html,'(A)') "      }"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "      // 2. INTI BINTANG GEMERLAP PELANGI KONSENTRIS"
  write(unit_html,'(A)') "      const coreCount = 90;"
  write(unit_html,'(A)') "      for (let i = 0; i < coreCount; i++) {"
  write(unit_html,'(A)') "        const angle = Math.random() * Math.PI * 2;"
  write(unit_html,'(A)') "        const speed = 1.2 + Math.random() * 3.2;"
  write(unit_html,'(A)') "        const vx = Math.cos(angle) * speed * 1.2;"
  write(unit_html,'(A)') "        const vy = Math.sin(angle) * speed * 1.2;"
  write(unit_html,'(A)') "        const col = rainbowPalette[i % rainbowPalette.length];"
  write(unit_html,'(A)') "        particles.push(new RainbowParticle(cx, cy, vx, vy, col, false, 80 + Math.random() * 25));"
  write(unit_html,'(A)') "      }"
  write(unit_html,'(A)') "    }"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "    function loop() {"
  write(unit_html,'(A)') "      ctx.globalCompositeOperation = 'destination-out';"
  write(unit_html,'(A)') "      ctx.fillStyle = 'rgba(0, 0, 0, 0.08)';"
  write(unit_html,'(A)') "      ctx.fillRect(0, 0, canvas.width, canvas.height);"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "      ctx.globalCompositeOperation = 'source-over';"
  write(unit_html,'(A)') ""
  write(unit_html,'(A)') "      // Roket Meluncur Naik"
  write(unit_html,'(A)') "      if (shellAscending) {"
  write(unit_html,'(A)') "        rocketTrail.push({x: rocketX, y: rocketY});"
  write(unit_html,'(A)') "        if (rocketTrail.length > 8) rocketTrail.shift();"
  write(unit_html,'(A)') "        rocketY += rocketVy;"
  write(unit_html,'(A)') "        rocketVy *= 0.985;"
  write(unit_html,'(A)') "        ctx.beginPath();"
  write(unit_html,'(A)') "        ctx.strokeStyle = '#ffffff';"
  write(unit_html,'(A)') "        ctx.lineWidth = 4.0;"
  write(unit_html,'(A)') "        for (let i = 0; i < rocketTrail.length; i++) {"
  write(unit_html,'(A)') "          ctx.lineTo(rocketTrail[i].x, rocketTrail[i].y);"
  write(unit_html,'(A)') "        }"
  write(unit_html,'(A)') "        ctx.stroke();"
