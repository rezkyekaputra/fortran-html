! ============================================================
! FORTRAN × DART SASS — PURE CSS FIREWORKS ENGINE 💥🎆
! Dibuat oleh: Cefneal & Imouto 🌸
! Menghitung Fisika Ledakan Kembang Api 360 Derajat
! Output: fireworks.scss & index.html
! ============================================================
program fireworks_engine
  implicit none

  integer :: unit_scss, unit_html
  integer :: b, p, f
  real :: angle, speed, r, x, y, gravity_drop
  real, parameter :: PI = 3.141592653589793
  character(len=20) :: burst_name(4)
  character(len=15) :: color_primary(4), color_secondary(4)
  real :: burst_x(4), burst_y(4), burst_delay(4)

  ! Definisi 4 Jenis Kembang Api Spektakuler
  burst_name = [character(len=20) :: "phoenix", "cyan-nova", "sakura-spark", "emerald-comet"]
  color_primary   = [character(len=15) :: "#fe8019", "#83a598", "#d3869b", "#b8bb26"]
  color_secondary = [character(len=15) :: "#fabd2f", "#8ec07c", "#fb4934", "#ebdbb2"]
  burst_x = [25.0, 75.0, 45.0, 80.0]
  burst_y = [28.0, 22.0, 40.0, 32.0]
  burst_delay = [0.0, 1.3, 2.5, 3.8]

  ! ------------------------------------------------------------
  ! 1. GENERATE SCSS DENGAN FISIKA FORTRAN
  ! ------------------------------------------------------------
  open(newunit=unit_scss, file="/home/dongkrak/fortran-web/fireworks.scss", status="replace")

  write(unit_scss,'(A)') "/// ========================================================="
  write(unit_scss,'(A)') "/// PURE CSS FIREWORKS ENGINE (FORTRAN × DART SASS) 💥🎆"
  write(unit_scss,'(A)') "/// Physics & Coordinates generated by GNU Fortran 14"
  write(unit_scss,'(A)') "/// Transpiled by Dart Sass 1.107.1"
  write(unit_scss,'(A)') "/// ========================================================="
  write(unit_scss,'(A)') "@use 'sass:math';"
  write(unit_scss,'(A)') "@use 'sass:color';"
  write(unit_scss,'(A)') ""
  write(unit_scss,'(A)') "* { margin: 0; padding: 0; box-sizing: border-box; }"
  write(unit_scss,'(A)') "body {"
  write(unit_scss,'(A)') "  background: radial-gradient(ellipse at bottom, #141617 0%, #080808 100%);"
  write(unit_scss,'(A)') "  min-height: 100vh;"
  write(unit_scss,'(A)') "  overflow: hidden;"
  write(unit_scss,'(A)') "  font-family: 'Segoe UI', -apple-system, monospace;"
  write(unit_scss,'(A)') "}"
  write(unit_scss,'(A)') ""
  write(unit_scss,'(A)') ".sky {"
  write(unit_scss,'(A)') "  position: relative;"
  write(unit_scss,'(A)') "  width: 100vw;"
  write(unit_scss,'(A)') "  height: 100vh;"
  write(unit_scss,'(A)') "}"
  write(unit_scss,'(A)') ""
  write(unit_scss,'(A)') ".overlay {"
  write(unit_scss,'(A)') "  position: absolute;"
  write(unit_scss,'(A)') "  top: 2rem;"
  write(unit_scss,'(A)') "  left: 50%;"
  write(unit_scss,'(A)') "  transform: translateX(-50%);"
  write(unit_scss,'(A)') "  text-align: center;"
  write(unit_scss,'(A)') "  z-index: 100;"
  write(unit_scss,'(A)') "  pointer-events: none;"
  write(unit_scss,'(A)') "  color: #ebdbb2;"
  write(unit_scss,'(A)') "}"
  write(unit_scss,'(A)') "h1 {"
  write(unit_scss,'(A)') "  font-size: 2.2rem;"
  write(unit_scss,'(A)') "  font-weight: 800;"
  write(unit_scss,'(A)') "  letter-spacing: -0.5px;"
  write(unit_scss,'(A)') "  background: linear-gradient(90deg, #fabd2f, #fe8019, #fb4934, #d3869b);"
  write(unit_scss,'(A)') "  -webkit-background-clip: text;"
  write(unit_scss,'(A)') "  -webkit-text-fill-color: transparent;"
  write(unit_scss,'(A)') "  text-shadow: 0 0 40px rgba(254, 128, 25, 0.6);"
  write(unit_scss,'(A)') "}"
  write(unit_scss,'(A)') ".sub {"
  write(unit_scss,'(A)') "  font-size: 0.95rem;"
  write(unit_scss,'(A)') "  color: #a89984;"
  write(unit_scss,'(A)') "  margin-top: 6px;"
  write(unit_scss,'(A)') "}"
  write(unit_scss,'(A)') ".pulse-dot {"
  write(unit_scss,'(A)') "  display: inline-block;"
  write(unit_scss,'(A)') "  width: 10px; height: 10px; border-radius: 50%;"
  write(unit_scss,'(A)') "  background: #fe8019; box-shadow: 0 0 12px #fe8019;"
  write(unit_scss,'(A)') "}"
  write(unit_scss,'(A)') ""
  write(unit_scss,'(A)') ".firework {"
  write(unit_scss,'(A)') "  position: absolute;"
  write(unit_scss,'(A)') "  width: 6px;"
  write(unit_scss,'(A)') "  height: 6px;"
  write(unit_scss,'(A)') "  border-radius: 50%;"
  write(unit_scss,'(A)') "}"

  ! Loop untuk 4 jenis ledakan kembang api
  do b = 1, 4
    write(unit_scss,'(A,A,A)') ".fw-", trim(burst_name(b)), " {"
    write(unit_scss,'(A,F5.1,A)') "  left: ", burst_x(b), "vw;"
    write(unit_scss,'(A,F5.1,A)') "  top: ", burst_y(b), "vh;"
    write(unit_scss,'(A,A,A,F4.1,A)') "  animation: burst-", trim(burst_name(b)), " 4.5s ease-out infinite ", burst_delay(b), "s;"
    write(unit_scss,'(A)') "}"
    write(unit_scss,'(A)') ""
    write(unit_scss,'(A,A,A)') "@keyframes burst-", trim(burst_name(b)), " {"
    
    ! 0%: Roket meluncur dari bawah layar
    write(unit_scss,'(A)') "  0% {"
    write(unit_scss,'(A)') "    transform: translateY(90vh) scale(1);"
    write(unit_scss,'(A,A,A)') "    background: ", trim(color_primary(b)), ";"
    write(unit_scss,'(A,A,A)') "    box-shadow: 0 0 15px ", trim(color_secondary(b)), ";"
    write(unit_scss,'(A)') "    opacity: 1;"
    write(unit_scss,'(A)') "  }"

    ! 48%: Sampai di titik ledakan di atas langit
    write(unit_scss,'(A)') "  48% {"
    write(unit_scss,'(A)') "    transform: translateY(0) scale(1.5);"
    write(unit_scss,'(A,A,A)') "    background: #ffffff;"
    write(unit_scss,'(A,A,A,A,A)') "    box-shadow: 0 0 35px #ffffff, 0 0 70px ", trim(color_primary(b)), ";"
    write(unit_scss,'(A)') "    opacity: 1;"
    write(unit_scss,'(A)') "  }"

    ! 50%: FLASH DUAR! Partikel mulai memencar dari titik 0
    write(unit_scss,'(A)') "  50% {"
    write(unit_scss,'(A)') "    background: transparent;"
    write(unit_scss,'(A)') "    opacity: 1;"
    write(unit_scss,'(A)') "    box-shadow:"
    do p = 1, 32
      if (p < 32) then
        write(unit_scss,'(A,A,A)') "      0 0 4px ", trim(color_primary(b)), ","
      else
        write(unit_scss,'(A,A,A)') "      0 0 4px ", trim(color_secondary(b)), ";"
      end if
    end do
    write(unit_scss,'(A)') "  }"

    ! 75%: Partikel mencapai radius ekspansi maksimum (Fisika Trigonometri Fortran!)
    write(unit_scss,'(A)') "  75% {"
    write(unit_scss,'(A)') "    background: transparent;"
    write(unit_scss,'(A)') "    opacity: 0.9;"
    write(unit_scss,'(A)') "    box-shadow:"
    do p = 1, 32
      angle = (real(p) / 32.0) * 2.0 * PI
      speed = 120.0 + mod(real(p) * 23.0, 60.0) ! Kecepatan dinamis per partikel
      x = speed * cos(angle)
      y = speed * sin(angle)
      if (mod(p, 2) == 0) then
        if (p < 32) then
          write(unit_scss,'(A,F7.2,A,F7.2,A,A,A)') "      ", x, "px ", y, "px 3px ", trim(color_primary(b)), ","
        else
          write(unit_scss,'(A,F7.2,A,F7.2,A,A,A)') "      ", x, "px ", y, "px 3px ", trim(color_primary(b)), ";"
        end if
      else
        if (p < 32) then
          write(unit_scss,'(A,F7.2,A,F7.2,A,A,A)') "      ", x, "px ", y, "px 3px ", trim(color_secondary(b)), ","
        else
          write(unit_scss,'(A,F7.2,A,F7.2,A,A,A)') "      ", x, "px ", y, "px 3px ", trim(color_secondary(b)), ";"
        end if
      end if
    end do
    write(unit_scss,'(A)') "  }"

    ! 100%: Partikel meluruh jatuh terpengaruh gravitasi bumi (g) & memudar
    write(unit_scss,'(A)') "  100% {"
    write(unit_scss,'(A)') "    background: transparent;"
    write(unit_scss,'(A)') "    opacity: 0;"
    write(unit_scss,'(A)') "    box-shadow:"
    do p = 1, 32
      angle = (real(p) / 32.0) * 2.0 * PI
      speed = 145.0 + mod(real(p) * 23.0, 60.0)
      gravity_drop = 65.0 ! Efek gravitasi
      x = speed * cos(angle)
      y = speed * sin(angle) + gravity_drop
      if (p < 32) then
        write(unit_scss,'(A,F7.2,A,F7.2,A,A,A)') "      ", x, "px ", y, "px 8px ", trim(color_secondary(b)), ","
      else
        write(unit_scss,'(A,F7.2,A,F7.2,A,A,A)') "      ", x, "px ", y, "px 8px ", trim(color_secondary(b)), ";"
      end if
    end do
    write(unit_scss,'(A)') "  }"

    write(unit_scss,'(A)') "}"
    write(unit_scss,'(A)') ""
  end do

  close(unit_scss)
  print *, "File fireworks.scss berhasil dibuat oleh Fortran!"

  ! ------------------------------------------------------------
  ! 2. GENERATE INDEX.HTML
  ! ------------------------------------------------------------
  open(newunit=unit_html, file="/home/dongkrak/fortran-web/index.html", status="replace")
  write(unit_html,'(A)') "<!DOCTYPE html>"
  write(unit_html,'(A)') "<html lang='id'>"
  write(unit_html,'(A)') "<head>"
  write(unit_html,'(A)') "  <meta charset='UTF-8'>"
  write(unit_html,'(A)') "  <meta name='viewport' content='width=device-width, initial-scale=1.0'>"
  write(unit_html,'(A)') "  <title>DUAR! Pure CSS Fireworks · Fortran × Dart Sass 💥</title>"
  write(unit_html,'(A)') "  <link rel='stylesheet' href='fireworks.css'>"
  write(unit_html,'(A)') "</head>"
  write(unit_html,'(A)') "<body>"
  write(unit_html,'(A)') "  <div class='overlay'>"
  write(unit_html,'(A)') "    <h1>💥 DUAR! KEMBANG API 🎆</h1>"
  write(unit_html,'(A)') "    <p class='sub'>"
  write(unit_html,'(A)') "      <span class='pulse-dot'></span> 100% Pure GPU CSS Animation · Zero JavaScript Overhead"
  write(unit_html,'(A)') "    </p>"
  write(unit_html,'(A)') "    <p style='color: #7c6f64; font-size: 0.8rem; margin-top: 6px;'>"
  write(unit_html,'(A)') "      Physics & Trajectories: <strong>GNU Fortran 14.3.1</strong> · Compiler: <strong>Dart Sass 1.107.1</strong>"
  write(unit_html,'(A)') "    </p>"
  write(unit_html,'(A)') "  </div>"
  write(unit_html,'(A)') "  <div class='sky'>"
  write(unit_html,'(A)') "    <div class='firework fw-phoenix'></div>"
  write(unit_html,'(A)') "    <div class='firework fw-cyan-nova'></div>"
  write(unit_html,'(A)') "    <div class='firework fw-sakura-spark'></div>"
  write(unit_html,'(A)') "    <div class='firework fw-emerald-comet'></div>"
  write(unit_html,'(A)') "  </div>"
  write(unit_html,'(A)') "</body>"
  write(unit_html,'(A)') "</html>"
  close(unit_html)
  print *, "File index.html berhasil dibuat!"

end program fireworks_engine
